-- The toasts, and what failed casts teach the button.

test("the pet dying toasts Revive Pet with the key to press", function()
    local client = NewClient():login()
    client.bindings["CLICK PetCareButton:LeftButton"] = "F"
    client:petDies()
    eq(client:toastTitle(), "Your pet is dead")
    eq(client.toast.Name.text, "Revive Pet")
    eq(client.toast.Icon.texture, 132163)
    eq(client.toast.Reason.text, "The button casts Revive Pet now, also once the body is gone.")
    eq(client.toast.Hint.text, "Press <F>.")
end)

test("without a key binding the hint names the macro", function()
    local client = NewClient():login():petDies()
    eq(client.toast.Hint.text, "Press your PetCare macro (/pcb macro makes one).")
end)

test("a pet that lives again takes the dead toast away", function()
    local client = NewClient():login():petDies():petGone():petBack()
    client:animate(1)
    eq(client.toast.shown, false)
end)

test("/pcb died off: no toast when the pet dies, the button still switches", function()
    local client = NewClient({ savedDB = { died = false } }):login():petDies():petGone()
    eq(client.toast.shown, false)
    eq(client:press(), "Revive Pet")
end)

test("combat starting without a pet toasts Call Pet; a dead pet toasts Revive Pet again", function()
    local client = NewClient({ noPet = true }):login():enterCombat()
    eq(client:toastTitle(), "You have no pet out")
    eq(client.toast.Name.text, "Call Pet")
    eq(client.toast.Reason.text, "Combat started without your pet.")
    client:petBack():animate(1)
    eq(client.toast.shown, false, "the pet came")
    client:petDies():petGone():leaveCombat()
    client.ns.HideToast()
    client:enterCombat()
    eq(client:toastTitle(), "Your pet is dead")
end)

test("combat starting with a pet out toasts nothing; the toggles silence the pull", function()
    local client = NewClient():login():enterCombat()
    eq(client.toast.shown, false)
    client = NewClient({ noPet = true, savedDB = { nopet = false } }):login():enterCombat()
    eq(client.toast.shown, false)
    client = NewClient({ noPet = true, savedDB = { died = false }, savedChar = { petDead = true } })
    client:login():enterCombat()
    eq(client.toast.shown, false)
end)

test("low health toasts Mend Pet once, again only after it went back above the line", function()
    local client = NewClient():login()
    client:petHealth(60)
    eq(client.toast.shown, false)
    client:petHealth(40)
    eq(client:toastTitle(), "Your pet is at 40% health")
    eq(client.toast.Name.text, "Mend Pet")
    client.ns.HideToast()
    client:petHealth(30)
    eq(client.toast.shown, false, "still low: no second toast")
    client:petHealth(80)
    client:petHealth(20)
    eq(client:toastTitle(), "Your pet is at 20% health")
end)

test("health going back up takes the low toast away; so does the pet dying", function()
    local client = NewClient():login():petHealth(10)
    client:petHealth(90):animate(1)
    eq(client.toast.shown, false)
    client:petHealth(10)
    eq(client:toastTitle(), "Your pet is at 10% health")
    client:petDies()
    eq(client:toastTitle(), "Your pet is at 10% health", "fading out")
    client:animate(1)
    eq(client:toastTitle(), "Your pet is dead")
end)

test("hidden health decides nothing until it can be read", function()
    local client = NewClient():login()
    client.healthSecret = true
    client:petHealth(10)
    eq(client.toast.shown, false)
    client.healthSecret = false
    client:fire("UNIT_MAXHEALTH", "pet")
    eq(client:toastTitle(), "Your pet is at 10% health")
end)

test("/pcb low 0 switches the low toast off and takes it away", function()
    local client = NewClient():login():petHealth(10)
    client:slash("low 0"):animate(1)
    eq(client.toast.shown, false)
    client:petHealth(5)
    eq(client.toast.shown, false)
end)

test("health of another unit is not looked at", function()
    local client = NewClient():login()
    client.pet.health = 10
    client:fire("UNIT_HEALTH", "target")
    eq(client.toast.shown, false)
end)

test("Call Pet failing without a pet switches the button to Revive Pet", function()
    local client = NewClient({ noPet = true }):login()
    eq(client:press(), "Call Pet")
    client:castFails(CALL)
    eq(client:press(), "Revive Pet")
    eq(client:toastTitle(), "Your pet is dead")
    eq(client.toast.Reason.text, "Call Pet failed: the button casts Revive Pet now.")
    eq(SavedChar().petDead, true)
end)

test("the error 'Your pet is dead' switches the button as well", function()
    local client = NewClient({ noPet = true }):login():uiError("Your pet is dead.")
    eq(client:press(), "Revive Pet")
end)

test("other errors, and a pet that exists, switch nothing", function()
    local client = NewClient({ noPet = true, savedDB = { debug = true } }):login()
    client:uiError("You are moving.")
    eq(client:press(), "Call Pet")
    ok(client:printedContains("error without a pet: You are moving."))
    client:uiError(SECRET):uiError(nil)
    client = NewClient():login():uiError("Your pet is dead."):uiError("Out of range.")
    eq(client:press(), "Mend Pet")
end)

test("Call Pet failing while mounted is not taken for a dead pet", function()
    local client = NewClient({ noPet = true }):login()
    client.mounted = true
    client:castFails(CALL)
    eq(client:press(), "Call Pet")
end)

test("in combat a failed Call Pet says to hold Shift and switches after combat", function()
    local client = NewClient({ noPet = true }):login():enterCombat()
    client.ns.HideToast()
    client:castFails(CALL)
    eq(client.toast.Reason.text, "Call Pet failed. In combat the button cannot switch: hold Shift for Revive Pet.")
    eq(client:press(), "Call Pet")
    eq(client:press({ shift = true }), "Revive Pet")
    eq(#client.blocked, 0, "it did not try")
    client:leaveCombat()
    eq(client:press(), "Revive Pet")
end)

test("a pet that came back during combat is not switched to dead after it", function()
    local client = NewClient({ noPet = true }):login():enterCombat():castFails(CALL)
    client:petBack():petGone():leaveCombat()
    eq(client:press(), "Call Pet")
end)

test("Revive Pet failing at once means no dead pet: back to Call Pet", function()
    local client = NewClient({ noPet = true, savedChar = { petDead = true } }):login()
    eq(client:press(), "Revive Pet")
    client:castFails(REVIVE)
    eq(client:press(), "Call Pet")
    ok(client:printedContains("Revive Pet failed, so there is no dead pet"))
end)

test("an interrupted Revive Pet keeps the button on Revive Pet", function()
    local client = NewClient({ noPet = true, savedChar = { petDead = true } }):login()
    client:castStarts(REVIVE, "Cast-7"):castFails(REVIVE, "Cast-7")
    eq(client:press(), "Revive Pet")
    client:castStarts(MEND, "Cast-8"):castStarts(REVIVE, SECRET)
end)

test("Revive Pet failing in combat, or on a body still there, switches nothing", function()
    local client = NewClient({ noPet = true, savedChar = { petDead = true } }):login():enterCombat()
    client:castFails(REVIVE)
    eq(client:press(), "Revive Pet")
    client = NewClient():login():petDies():castFails(REVIVE)
    eq(client:press(), "Revive Pet")
    client = NewClient({ noPet = true }):login():castFails(REVIVE)
    eq(client:press(), "Call Pet")
end)

test("hidden cast values and other spells are left alone", function()
    local client = NewClient({ noPet = true }):login()
    client:castFails(SECRET):castFails(CALL, SECRET):castFails(MEND)
    eq(client:press(), "Call Pet")
end)

test("a cast of another unit is not looked at", function()
    local client = NewClient({ noPet = true }):login()
    client:fire("UNIT_SPELLCAST_FAILED", "pet", "Cast-1", CALL)
    eq(client:press(), "Call Pet")
end)

test("debug traces what was learned", function()
    local client = NewClient({ noPet = true, savedDB = { debug = true } }):login():castFails(CALL)
    ok(client:printedContains("pet is dead: Call Pet failed"))
    ok(client:printedContains("pet counted as dead"))
    client:petBack():petHealth(30)
    ok(client:printedContains("low: 30%"))
end)
