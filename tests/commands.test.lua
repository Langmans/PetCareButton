end)

test("/pcb duration and scale, clamped, or the status without a number", function()
    local client = NewClient():login()
    client:slash("duration 0.4")
    eq(Saved().duration, 1)
    client:slash("duration 12.7")
    eq(Saved().duration, 12)
    ok(client:printedContains("Toast duration: 12 seconds."))
    client:slash("scale 9")
    eq(Saved().scale, 3)
    client:slash("scale 0.1")
    eq(Saved().scale, 0.3)
    ok(client:printedContains("Toast scale: 0.30."))
    client.printed = {}
    client:slash("duration"):slash("scale big")
    eq(#client.printed, 2)
    ok(client:printedContains("Commands:"))
end)

test("/pcb reset forgets the dragged spot", function()
    local client = NewClient({ savedDB = { pos = { "TOP", "TOP", 1, 2 } } }):login():slash("reset")
    eq(Saved().pos, nil)
    ok(client:printedContains("Toast position reset."))
end)

test("/pcb debug toggles the trace", function()
    local client = NewClient():login():slash("debug")
    eq(Saved().debug, true)
    ok(client:printedContains("Debug on."))
    client:slash("debug")
    eq(Saved().debug, false)
    ok(client:printedContains("Debug off."))
end)

