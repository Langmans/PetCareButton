-- /pcb and its subcommands.

test("/pcb alone, or anything unknown, shows the status and the commands", function()
    local client = NewClient():login():slash("")
    ok(client:printedContains("Without a pet the button casts Call Pet."))
    ok(client:printedContains("Toasts: pet died on, no pet at the pull on, low health at 40%."))
    ok(client:printedContains("Toast for 6 s at scale 1.00, sound your pet's own, debug off."))
    ok(client:printedContains("/pcb macro"))
    client.printed = {}
    client:slash("nonsense")
    ok(client:printedContains("Commands:"))
end)

test("the status shows a dead pet and low health off", function()
    local client = NewClient({ savedDB = { low = 0 }, savedChar = { petDead = true }, noPet = true }):login()
    client:slash("")
    ok(client:printedContains("Without a pet the button casts Revive Pet."))
    ok(client:printedContains("low health off."))
end)

test("/pcb on another class says the button does nothing", function()
    local client = NewClient({ class = "MAGE" }):login():slash("")
    ok(client:printedContains("Only hunters have Mend Pet"))
    client.printed = {}
    client:slash("revive")
    ok(client:printedContains("Only hunters have Mend Pet"))
end)

test("/pcb revive and call set what the button does without a pet", function()
    local client = NewClient({ noPet = true }):login():slash("revive")
    eq(client:press(), "Revive Pet")
    ok(client:printedContains("Your pet counts as dead"))
    client:slash("call")
    eq(client:press(), "Call Pet")
    ok(client:printedContains("Your pet counts as alive"))
end)

test("/pcb revive in combat is refused", function()
    local client = NewClient({ noPet = true }):login():enterCombat():slash("revive")
    eq(client:press(), "Call Pet")
    ok(client:printedContains("Not in combat"))
    eq(#client.blocked, 0)
end)

test("/pcb died and nopet take on and off", function()
    local client = NewClient():login()
    client:slash("died off")
    eq(Saved().died, false)
    ok(client:printedContains("No toast when your pet dies."))
    client:slash("nopet off")
    eq(Saved().nopet, false)
    client:slash("died on"):slash("nopet ON")
    eq(Saved().died, true)
    eq(Saved().nopet, true)
    ok(client:printedContains("A toast when combat starts without a pet."))
    client.printed = {}
    client:slash("died maybe")
    ok(client:printedContains("Commands:"), "anything else shows the status")
end)

test("/pcb low takes a whole percentage from 0 to 90", function()
    local client = NewClient():login()
    client:slash("low 25.7")
    eq(Saved().low, 25)
    ok(client:printedContains("A toast when your pet drops to 25% health."))
    client:slash("low 200")
    eq(Saved().low, 90)
    client:slash("low 0")
    eq(Saved().low, 0)
    ok(client:printedContains("No toast for low health."))
    client.printed = {}
    client:slash("low")
    ok(client:printedContains("Commands:"))
end)

test("/pcb low raised over the pet's health toasts at once", function()
    local client = NewClient():login():petHealth(50)
    eq(client.toast.shown, false)
    client:slash("low 60")
    eq(client:toastTitle(), "Your pet is at 50% health")
end)

test("/pcb test shows a toast of each kind without touching real ones", function()
    local client = NewClient():login():slash("test")
    eq(client:toastTitle(), "Your pet is dead")
    client.ns.HideToast()
    client:slash("test nopet")
    eq(client:toastTitle(), "You have no pet out")
    client.ns.HideToast()
    client:slash("test low")
    eq(client:toastTitle(), "Your pet is at 40% health")
    client:petDies()
    client.ns.HideToast()
    eq(client:toastTitle(), "Your pet is dead", "the real alert still has its own toast")
end)

test("/pcb sound family, on, warning and off", function()
    local client = NewClient():login()
