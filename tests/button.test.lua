-- What pressing the button casts: the macro conditions plus the remembered death, in and out of
-- combat, and what is saved for the next login.

test("a living pet gets Mend Pet; Shift forces Revive Pet and Ctrl Call Pet", function()
    local client = NewClient():login()
    eq(client:press(), "Mend Pet")
    eq(client:press({ shift = true }), "Revive Pet")
    eq(client:press({ ctrl = true }), "Call Pet")
end)

test("no pet that is known to be alive gets Call Pet", function()
    local client = NewClient({ noPet = true }):login()
    eq(client:press(), "Call Pet")
end)

test("a pet that dies gets Revive Pet, also once its body is gone, also in combat", function()
    local client = NewClient():login():enterCombat()
    client:petDies()
    eq(client:press(), "Revive Pet", "the body is still there")
    client:petGone()
    eq(client:press(), "Revive Pet", "the plain macro would pick Call Pet here")
    eq(client:press({ ctrl = true }), "Call Pet", "Ctrl still forces Call Pet")
    eq(#client.blocked, 0, "only secure code changed the button")
    client:petBack()
    eq(client:press(), "Mend Pet")
    client:petGone()
    eq(client:press(), "Call Pet", "a living pet dismissed is called again")
end)

test("the death is saved per character and known again after a relog", function()
    local client = NewClient():login():petDies()
    eq(SavedChar().petDead, true)
    local relogged = NewClient({ noPet = true, savedChar = SavedChar() }):login()
    eq(relogged:press(), "Revive Pet")
    eq(relogged.ns.PetDead(), true)
end)

test("a broken per-character save counts the pet as alive", function()
    local client = NewClient({ noPet = true, savedChar = "broken" }):login()
    eq(client:press(), "Call Pet")
    eq(SavedChar().petDead, false)
    client = NewClient({ noPet = true, savedChar = { petDead = "yes" } }):login()
    eq(client:press(), "Call Pet")
end)

test("loaded in combat, the button is set up once combat ends", function()
    local client = NewClient({ inCombat = true }):login()
    eq(client:press(), nil, "nothing set up yet")
    eq(#client.blocked, 0, "nothing was tried")
    client:leaveCombat()
    eq(client:press(), "Mend Pet")
    client:enterCombat():leaveCombat()
    eq(client:press(), "Mend Pet", "set up only once")
end)

test("the button acts on release and answers to up and down clicks", function()
    local client = NewClient():login()
    eq(client.button.clicks[1], "AnyUp")
    eq(client.button.clicks[2], "AnyDown")
    eq(client.button.attributes.useOnKeyDown, false)
end)

test("the macro uses the client's spell names", function()
    local client = NewClient({ locale = "deDE" }):login()
    eq(client:press(), "Tier heilen")
    eq(client:press({ shift = true }), "Tier wiederbeleben")
    eq(client:press({ ctrl = true }), "Tier rufen")
end)

test("without spell names from the client the English ones are used", function()
    local client = NewClient({ noSpellAPI = true }):login()
    eq(client:press(), "Mend Pet")
end)

test("on another class the button is not set up", function()
    local client = NewClient({ class = "MAGE" }):login()
    eq(client:press(), nil)
    eq(#client.drivers, 0)
end)

test("the key binding has a header and a name", function()
    NewClient():login()
    eq(BINDING_HEADER_PETCAREBUTTON, "Pet Care Button")
    eq(_G["BINDING_NAME_CLICK PetCareButton:LeftButton"], "Mend, revive or call pet")
end)

test("debug traces how the button counts the pet", function()
    local client = NewClient({ savedDB = { debug = true } }):login()
    ok(client:printedContains("button ready, pet counted as not dead"))
    client:petDies()
    ok(client:printedContains("pet: dead"))
end)
